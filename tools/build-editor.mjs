import {readFile, writeFile} from "node:fs/promises";

const [template, script] = (await Promise.all([
  readFile(new URL("../src/editor/editor.template.html", import.meta.url), "utf8"),
  readFile(new URL("../build/editor/editor.js", import.meta.url), "utf8")
])).map(text => text.replace(/\r\n?/g, "\n"));
const marker = "/* @editor-script */";
const parts = template.split(marker);
if (parts.length !== 2 || /<\/script/i.test(script)) {
  throw new Error("The editor template or compiled script cannot be embedded safely.");
}
const banner = "<!-- Generated by npm run build. Sources are in src/editor/. -->";
const output = new URL("../modbus-regmap-editor.html", import.meta.url);
const draftSlot = /(<script id="html-project-data" type="application\/json">)([^<]*)(<\/script>)/;
const existing = await readFile(output, "utf8").catch(error => {
  if (error.code === "ENOENT") return "";
  throw error;
});
const savedDraft = existing.match(draftSlot)?.[2];
const html = parts.join(script.trimEnd()).replace("<!doctype html>", "<!doctype html>\n" + banner);
await writeFile(output, savedDraft === undefined ? html :
  html.replace(draftSlot, (_, open, _empty, close) => open + savedDraft + close), "utf8");
